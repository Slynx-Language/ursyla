use std::path::Path;

use color_eyre::eyre::eyre;
use serde::Deserialize;

pub const CONFIG_FILE_NAME: &str = "ursyla.toml";
pub const DEFAULT_INPUT: &str = "src/main.slx";

crate::ursyla_fields! {
    ProjectConfig, ProjectFlags {
        /// Profile to run, read from ~/.config/ursyla/<profile>.toml
        #[arg(required_unless_present = "exec", required_unless_present="list_profiles")]
        profile: Option<String> = None,

        /// Where the result of the compilation is written
        #[arg(required_unless_present = "exec", required_unless_present="list_profiles")]
        output: Option<String> = None,

        /// Binary used to compile, defaults to the binary of the profile
        runner: Option<String> = None,

        /// Slynx entry file, relative to the project root
        input: Option<String> = Some(DEFAULT_INPUT.to_string()),
    }
}

/// Helpers that need more than the merge generated by `ursyla_fields`.
impl ProjectConfig {
    pub fn entry(&self) -> &str {
        self.input.as_deref().unwrap_or(DEFAULT_INPUT)
    }
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(default)]
pub struct UrsylaConfig {
    pub project: ProjectConfig,
}

impl UrsylaConfig {
    pub fn profile_name(&self) -> color_eyre::Result<&str> {
        self.project.profile.as_deref().ok_or_else(|| {
            eyre!(
                "no profile defined, give `--profile` or set `project.profile` on '{}'",
                CONFIG_FILE_NAME
            )
        })
    }
}

pub fn load(project_root: &Path) -> color_eyre::Result<UrsylaConfig> {
    let file = project_root.join(CONFIG_FILE_NAME);
    let content = std::fs::read_to_string(&file)
        .map_err(|err| eyre!("could not read '{}': {}", file.display(), err))?;
    toml::from_str(&content).map_err(|err| eyre!("could not parse '{}': {}", file.display(), err))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn missing_keys_fall_back_to_the_declared_default() {
        let config: UrsylaConfig = toml::from_str("[project]\nprofile = \"js\"").unwrap();

        assert_eq!(config.project.profile.as_deref(), Some("js"));
        assert_eq!(config.project.input.as_deref(), Some(DEFAULT_INPUT));
        assert_eq!(config.project.output, None);
        assert_eq!(config.project.runner, None);
    }

    #[test]
    fn given_flags_overwrite_the_file() {
        let mut config: UrsylaConfig = toml::from_str(
            "[project]\nprofile = \"js\"\noutput = \"out.js\"\ninput = \"src/other.slx\"",
        )
        .unwrap();
        let flags = ProjectFlags {
            profile: None,
            output: Some("dist/out.js".to_string()),
            runner: Some("slynx-to-js".to_string()),
            input: None,
        };

        config.project.merge(&flags);

        assert_eq!(config.project.profile.as_deref(), Some("js"));
        assert_eq!(config.project.input.as_deref(), Some("src/other.slx"));
        assert_eq!(config.project.output.as_deref(), Some("dist/out.js"));
        assert_eq!(config.project.runner.as_deref(), Some("slynx-to-js"));
    }

    #[test]
    fn a_profile_is_required_to_build_an_invocation() {
        let config = UrsylaConfig::default();

        assert!(config.profile_name().is_err());
    }
}
